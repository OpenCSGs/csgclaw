func (h *Handler) Routes() chi.Router {
	h.EnableConversationResources()
	router := chi.NewRouter()
	router.Use(h.authorizeAppPlatformRequests)
	h.registerCoreRoutes(router)
	h.registerChannelRoutes(router)
	return router
}

