package installstate

import (
	"os"
	"path/filepath"
	"testing"
)

func writeHashFixture(t *testing.T, root, path, content string) {
	t.Helper()
	target := filepath.Join(root, filepath.FromSlash(path))
	if err := os.MkdirAll(filepath.Dir(target), 0755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(target, []byte(content), 0644); err != nil {
		t.Fatal(err)
	}
}

func TestBuiltinHashIgnoresPythonBytecodeOnly(t *testing.T) {
	for _, change := range []struct {
		name, path, content string
		cache               bool
	}{
		{"cache_directory", "scripts/office/__pycache__/soffice.cpython-313.pyc", "bytecode", true},
		{"legacy_bytecode", "scripts/helper.pyc", "bytecode", true},
		{"optimized_bytecode", "scripts/helper.pyo", "bytecode", true},
		{"edited_source", "scripts/helper.py", "user source edit", false},
		{"edited_instructions", "SKILL.md", "user instructions", false},
		{"added_user_file", "scripts/user-helper.py", "user source", false},
		{"added_user_asset", "assets/user.txt", "user asset", false},
	} {
		t.Run(change.name, func(t *testing.T) {
			root := t.TempDir()
			writeHashFixture(t, root, "SKILL.md", "instructions")
			writeHashFixture(t, root, "scripts/helper.py", "source")
			baseline, err := BundleSHA256(root)
			if err != nil {
				t.Fatal(err)
			}
			clean, err := BuiltinBundleSHA256(root)
			if err != nil || clean != baseline {
				t.Fatalf("clean bundle hash changed: %v", err)
			}
			writeHashFixture(t, root, change.path, change.content)
			exact, err := BundleSHA256(root)
			if err != nil {
				t.Fatal(err)
			}
			if exact == baseline {
				t.Fatal("exact bundle hash ignored a changed file")
			}
			filtered, err := BuiltinBundleSHA256(root)
			if err != nil {
				t.Fatal(err)
			}
			if (filtered == baseline) != change.cache {
				t.Fatalf("cache=%t: source hash equal=%t", change.cache, filtered == baseline)
			}
		})
	}
}

func TestBuiltinActivationRecoveryWithPythonCache(t *testing.T) {
	root := t.TempDir()
	dst := filepath.Join(root, "xlsx")
	writeHashFixture(t, dst, "SKILL.md", "current bundled revision")
	writeHashFixture(t, dst, "scripts/office/soffice.py", "bundled source")
	hash, err := BundleSHA256(dst)
	if err != nil {
		t.Fatal(err)
	}
	old := Record{Source: SourceBuiltin, Version: "old", SHA256: "old"}
	if err := Update(root, "xlsx", &old, nil); err != nil {
		t.Fatal(err)
	}
	stage := filepath.Join(root, ".builtin-staging", ".builtin-stage-test")
	writeHashFixture(t, stage+".previous", "SKILL.md", "old bundled revision")
	if err := WriteBuiltinActivation(root, "xlsx", stage, hash); err != nil {
		t.Fatal(err)
	}
	writeHashFixture(t, dst, "scripts/office/__pycache__/soffice.cpython-313.pyc", "generated bytecode")
	// The replacement is active but the process exited before committing origins.
	recovered, commit, err := RecoverBuiltinActivation(root, "xlsx", old)
	if err != nil {
		t.Fatalf("cache blocked activation recovery: %v", err)
	}
	if !commit || recovered.Version != hash || recovered.SHA256 != hash {
		t.Fatalf("did not recover current bundled origin: %+v", recovered)
	}
	// A genuine source edit must not be accepted as the interrupted bundled copy.
	writeHashFixture(t, dst, "scripts/office/soffice.py", "user source edit")
	if _, _, err := RecoverBuiltinActivation(root, "xlsx", old); err == nil {
		t.Fatal("user edit was adopted as an unmodified bundled activation")
	}
}
